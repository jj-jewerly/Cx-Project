class SimCamera(Camera):
    """Generates Pillow test frames or static JPEG fallback."""

    def __init__(self, camera_type: str, fps: int = 10) -> None:
        self._type = camera_type
        self._fps = fps
        self._frame_num = 0

    @property
    def name(self) -> str:
        return f"sim_{self._type}"

    @property
    def fps(self) -> int:
        return self._fps

    async def init(self) -> bool:
        return True

    async def get_frame(self) -> bytes:
        self._frame_num += 1
        if HAS_PILLOW:
            return _generate_pillow_frame(self._type, self._frame_num)
        return STATIC_JPEG

    async def snapshot(self, path: str) -> str:
        frame = await self.get_frame()
        filename = f"{self._type}_{int(time.time() * 1000)}.jpg"
        filepath = f"{path}/{filename}"
        with open(filepath, "wb") as f:
            f.write(frame)
        return filename

    async def close(self) -> None:
        pass


def _generate_pillow_frame(camera_type: str, frame_num: int) -> bytes:
    """Generate a test JPEG frame using Pillow."""
    w, h = 320, 240
    t = frame_num / 10.0

    if camera_type == "rgb":
        r = int(40 + 30 * math.sin(t))
        g = int(60 + 30 * math.sin(t + 2))
        b = int(80 + 30 * math.sin(t + 4))
        img = Image.new("RGB", (w, h), (r, g, b))
        draw = ImageDraw.Draw(img)
        cx, cy = w // 2, h // 2
        draw.line([(cx - 20, cy), (cx + 20, cy)], fill=(0, 255, 0), width=1)
        draw.line([(cx, cy - 20), (cx, cy + 20)], fill=(0, 255, 0), width=1)
        draw.text((10, 10), f"RGB #{frame_num}", fill=(255, 255, 255))
    else:
        # Thermal-like gradient
        base = int(128 + 40 * math.sin(t * 0.3))
        img = Image.new("RGB", (w, h))
        for y_pos in range(h):
            v = int(base + (y_pos / h) * 60)
            rv = min(255, v + 40)
            gv = min(255, v - 20)
            bv = max(0, v - 80)
            for x_pos in range(w):
                img.putpixel((x_pos, y_pos), (rv, gv, bv))
        draw = ImageDraw.Draw(img)
        draw.text((10, 10), f"THERMAL #{frame_num}", fill=(255, 255, 0))
        spot_x = int(w / 2 + 50 * math.sin(t * 0.5))
        spot_y = int(h / 2 + 30 * math.cos(t * 0.7))
        draw.ellipse(
            [(spot_x - 15, spot_y - 15), (spot_x + 15, spot_y + 15)],
            fill=(255, 100, 0),
        )

    buf = io.BytesIO()
    img.save(buf, format="JPEG", quality=60)
    return buf.getvalue()
